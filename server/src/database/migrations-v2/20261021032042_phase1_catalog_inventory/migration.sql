-- Keep released/issued history as well as active reservations. No historical stock is re-applied.
INSERT INTO inventory_reservation (order_id,location_id,variant_id,quantity,state)
SELECT cs.order_id,(r->>'locationId')::uuid,(r->>'variantId')::uuid,sum((r->>'quantity')::integer),
CASE WHEN o.order_status IN ('completed','returned') THEN 'issued'
     WHEN o.order_status='cancelled' OR cs.state IN ('cancelled','failed') THEN 'released' ELSE 'reserved' END
FROM checkout_session cs JOIN sales_order o ON o.id=cs.order_id CROSS JOIN LATERAL jsonb_array_elements(cs.reservations) r
GROUP BY cs.order_id,(r->>'locationId')::uuid,(r->>'variantId')::uuid,o.order_status,cs.state;
